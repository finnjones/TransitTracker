/**
 * The sprite sheets generated by `tools/sprites/make_sprites.py --app …` (see its docstring).
 * All sizes are in art pixels (dots) and include 1 dot of padding on every side.
 *
 * [groundRow] is the row the vehicle stands on (the first row under its wheels; the waterline for
 * the ferry): strips put that row on the rail / road / water. [bodyLeft]..[bodyRight] is the
 * vehicle without the speed-line margin behind it; strips centre the body on a stop.
 */
enum class SpriteSheet(
    val frameWidth: Int,
    val frameHeight: Int,
    val frames: Int,
    val groundRow: Int,
    val bodyLeft: Int,
) {
    TRAIN(32, 16, 5, 15, 5),
    METRO(32, 16, 5, 15, 5),
    LIGHT_RAIL(36, 16, 5, 14, 5),
    BUS(30, 15, 5, 14, 5),
    COACH(34, 15, 5, 14, 5),
    FERRY(34, 18, 5, 13, 1),
    OTHER(19, 16, 5, 13, 5),
    TRAIN_LONG(113, 16, 5, 15, 5),
    METRO_LONG(113, 16, 5, 15, 5),
    LIGHT_RAIL_PAIR(67, 16, 5, 14, 5),
    /** Walk 0-3, stand 4, run 5-8. */
    WALKER(10, 14, 9, 13, 1),
    ;

    val bodyRight: Int get() = frameWidth - 1

    companion object {
        /** Frames 0-3 of a vehicle sheet are the moving cycle. */
        const val MOVING_FRAMES = 4
        /** Frame 4 of a vehicle sheet stands still with its doors open and lit. */
        const val STOPPED_FRAME = 4

        /** The everyday sprite for [mode]; [long] picks the page-transition consist where one exists. */
        fun forMode(mode: Mode, long: Boolean = false): SpriteSheet = when (mode) {
            Mode.TRAIN -> if (long) TRAIN_LONG else TRAIN
            Mode.METRO -> if (long) METRO_LONG else METRO
            Mode.LIGHT_RAIL -> if (long) LIGHT_RAIL_PAIR else LIGHT_RAIL
            Mode.BUS -> BUS
            Mode.COACH -> COACH
            Mode.FERRY -> FERRY
            Mode.OTHER -> OTHER
        }
    }
}

/** The three layers of one sheet, loaded. */
@Immutable
class SpriteImages(val base: ImageBitmap, val livery: ImageBitmap, val outline: ImageBitmap)

private fun SpriteSheet.resources(): Triple<DrawableResource, DrawableResource, DrawableResource> = when (this) {
    SpriteSheet.TRAIN -> Triple(Res.drawable.sprite_train, Res.drawable.sprite_train_livery, Res.drawable.sprite_train_outline)
    SpriteSheet.METRO -> Triple(Res.drawable.sprite_metro, Res.drawable.sprite_metro_livery, Res.drawable.sprite_metro_outline)
    SpriteSheet.LIGHT_RAIL -> Triple(Res.drawable.sprite_lightrail, Res.drawable.sprite_lightrail_livery, Res.drawable.sprite_lightrail_outline)
    SpriteSheet.BUS -> Triple(Res.drawable.sprite_bus, Res.drawable.sprite_bus_livery, Res.drawable.sprite_bus_outline)
    SpriteSheet.COACH -> Triple(Res.drawable.sprite_coach, Res.drawable.sprite_coach_livery, Res.drawable.sprite_coach_outline)
    SpriteSheet.FERRY -> Triple(Res.drawable.sprite_ferry, Res.drawable.sprite_ferry_livery, Res.drawable.sprite_ferry_outline)
    SpriteSheet.OTHER -> Triple(Res.drawable.sprite_other, Res.drawable.sprite_other_livery, Res.drawable.sprite_other_outline)
    SpriteSheet.TRAIN_LONG -> Triple(Res.drawable.sprite_train_long, Res.drawable.sprite_train_long_livery, Res.drawable.sprite_train_long_outline)
    SpriteSheet.METRO_LONG -> Triple(Res.drawable.sprite_metro_long, Res.drawable.sprite_metro_long_livery, Res.drawable.sprite_metro_long_outline)
    SpriteSheet.LIGHT_RAIL_PAIR -> Triple(Res.drawable.sprite_lightrail_pair, Res.drawable.sprite_lightrail_pair_livery, Res.drawable.sprite_lightrail_pair_outline)
    SpriteSheet.WALKER -> Triple(Res.drawable.sprite_walker, Res.drawable.sprite_walker_livery, Res.drawable.sprite_walker_outline)
}

@Composable
fun rememberSpriteImages(sheet: SpriteSheet): SpriteImages {
    val (b, l, o) = sheet.resources()
    // imageResource caches per resource, so this is cheap to call from every sprite.
    return SpriteImages(imageResource(b), imageResource(l), imageResource(o))
}

/** How a frame is coloured (the per-state treatments of plan 3.2). */
enum class SpriteLook {
    NORMAL,
    /** Grey and faded: timetable only. */
    GHOST,
    /** Faded, colour kept: stale live data. */
    FADED,
    /** Grey and very faint, under a red cross: cancelled. */
    CANCELLED,
}

private val greyscale = ColorFilter.colorMatrix(ColorMatrix().apply { setToSaturation(0f) })

private fun grey(c: Color): Color {
    val l = 0.2126f * c.red + 0.7152f * c.green + 0.0722f * c.blue
    return Color(l, l, l, c.alpha)
}

/**
 * Draws one frame of [sheet] with its top-left at ([left], [top]) device pixels, [cellPx] device
 * pixels per art pixel, never smoothed. The livery mask is tinted with [livery]; [outline] (Day
 * theme) draws the 1-dot outline first. [mirror] flips it to face left.
 */
fun DrawScope.drawSpriteFrame(
    sheet: SpriteSheet,
    images: SpriteImages,
    frame: Int,
    left: Float,
    top: Float,
    cellPx: Int,
    livery: Color,
    look: SpriteLook = SpriteLook.NORMAL,
    outline: Color? = null,
    mirror: Boolean = false,
) {
    val src = IntOffset(frame.coerceIn(0, sheet.frames - 1) * sheet.frameWidth, 0)
    val srcSize = IntSize(sheet.frameWidth, sheet.frameHeight)
    val dst = IntOffset(left.toInt(), top.toInt())
    val dstSize = IntSize(sheet.frameWidth * cellPx, sheet.frameHeight * cellPx)
    val alpha = when (look) {
        SpriteLook.NORMAL -> 1f
        SpriteLook.GHOST -> 0.45f
        SpriteLook.FADED -> 0.6f
        SpriteLook.CANCELLED -> 0.3f
    }
    val grey = look == SpriteLook.GHOST || look == SpriteLook.CANCELLED
    val liveryColor = if (grey) grey(livery) else livery
    val draw: DrawScope.() -> Unit = {
        if (outline != null) {
            drawImage(images.outline, src, srcSize, dst, dstSize, alpha, colorFilter = ColorFilter.tint(outline, BlendMode.SrcIn), filterQuality = FilterQuality.None)
        }
        drawImage(images.base, src, srcSize, dst, dstSize, alpha, colorFilter = if (grey) greyscale else null, filterQuality = FilterQuality.None)
        drawImage(images.livery, src, srcSize, dst, dstSize, alpha, colorFilter = ColorFilter.tint(liveryColor, BlendMode.SrcIn), filterQuality = FilterQuality.None)
    }
    if (mirror) {
        scale(-1f, 1f, pivot = Offset(dst.x + dstSize.width / 2f, dst.y + dstSize.height / 2f), block = draw)
    } else draw()
}
